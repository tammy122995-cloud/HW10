import sys

# ------------------ 共同設定 ------------------
student_id = input("請輸入完整學號：").strip().upper()
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

print(f"\n{'='*20} 共同設定確認 {'='*20}")
print(f"學號: {student_id}, 末三碼: {tail}, a={a}, b={b}, c={c}, s={s}\n")
# =====================================================================
# 第 4 題：清理素材點擊資料並產生排名
# =====================================================================
print(f"{'='*20} 第 4 題 {'='*20}")
raw_clicks = [str(10 + a), "0", "", " " + str(5 + b) + " ", "   ", str(15 + c), str(5 + b)]
min_clicks = 5 + b

def select_clicks(raw_clicks, min_clicks=10):
    # 1. map() 搭配 lambda 去掉每筆文字的頭尾空白
    step1 = map(lambda x: x.strip(), raw_clicks)
    # 2. filter(None, ...) 刪掉空字串
    step2 = filter(None, step1)
    # 3. map(int, ...) 轉整數，並用 list() 保存
    numbers = list(map(int, step2))
    # 4. filter() 搭配 lambda 篩選大於或等於 min_clicks 的項目
    qualified = list(filter(lambda x: x >= min_clicks, numbers))
    return (numbers, qualified)

numbers, qualified = select_clicks(raw_clicks, min_clicks=min_clicks)

print(f"學號：{student_id}")
print(f"點擊門檻：{min_clicks}")
print(f"清理結果：{numbers}")
print(f"合格結果：{qualified}")
print(f"合格筆數：{len(qualified)}")
print(f"合格合計：{sum(qualified)}")

sorted_qualified = sorted(qualified, reverse=True)
if sorted_qualified:
    for idx, clicks_val in enumerate(sorted_qualified, start=1):
        print(f"第{idx}名：{clicks_val}次")
else:
    print("無符合門檻的素材")

# 以門檻 100 呼叫
num_100, qual_100 = select_clicks(raw_clicks, min_clicks=100)
print(f"門檻100合格結果：{qual_100}")
print(f"門檻100合格筆數：{len(qual_100)}")
print(f"門檻100合格合計：{sum(qual_100)}")
if not qual_100:
    print("無符合門檻的素材")