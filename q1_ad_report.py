import sys

# ------------------ 共同設定 ------------------
student_id = input("請輸入完整學號：").strip().upper()
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

print(f"\n{'='*20} 共同設定確認 {'='*20}")
print(f"學號: {student_id}, 末三碼: {tail}, a={a}, b={b}, c={c}, s={s}\n")

# =====================================================================
# 第 1 題：製作自己的廣告成效報表
# =====================================================================
print(f"{'='*20} 第 1 題 {'='*20}")
ads = [
    ("搜尋廣告", 1000 + 100 * a, 30 + 5 * b),
    ("社群廣告", 1200 + 100 * b, 24 + 4 * c),
    ("影音廣告", 0, 0),
]
target = 2.5 + 0.1 * c

def ad_report(impressions, clicks, target=3.0):
    if impressions == 0:
        return (None, False)
    ctr = clicks / impressions * 100
    passed = ctr >= target
    return (ctr, passed)

passed_count = 0
print(f"學號：{student_id}")
print(f"CTR門檻：{target:.2f}%")

for name, imp, clk in ads:
    ctr_val, is_passed = ad_report(imp, clk, target=target)
    if ctr_val is None:
        ctr_str = "無曝光資料"
    else:
        ctr_str = f"{ctr_val:.2f}%"
    print(f"{name}：曝光={imp}，點擊={clk}，CTR={ctr_str}，達標={is_passed}")
    if is_passed:
        passed_count += 1

print(f"達標廣告數：{passed_count}")

# 測試額外呼叫
t1_ctr, t1_pass = ad_report(1000, 30)
print(f"預設門檻測試：({t1_ctr:.1f}, {t1_pass})")
t2_ctr, t2_pass = ad_report(1000, 0)
print(f"零點擊測試：({t2_ctr:.1f}, {t2_pass})")
print()